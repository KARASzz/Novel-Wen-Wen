import re
path = r'D:\+Python\Novel-Wen-Wen\第二卷\第51章_午餐肉涨价_正文_v1.md'
with open(path, 'r', encoding='utf-8') as f:
    text = f.read()

replacements = [
    # 「不是——写不出来——她——是——想——清楚」→ 改成「写不出来,她想清楚再写」
    ('她——**不是**——**写不出来**——**她**——**是**——**想**——**清楚**——**再写**。',
     '她**写不出来**——**她**——**想清楚**——**再写**。'),
    # 「她——问——梅——的——不是——字——对不对」 → 「她问梅的不是字对不对」
    ('她——问——梅——的——不是——字——对不对。',
     '她问梅的不是字对不对。'),
    # 「不是——一个人——写——的」 → 「不是一个人写的」
    ('莉莉娅自己答:**同款**——**的**——**包装**——**的**——**字**——**不是**——**一个人**——**写**——**的**。',
     '莉莉娅自己答:**同款**——**的**——**包装**——**的**——**字**——**不是**——**一个人写的**。'),
    # 「不是——广告——部——写——的」 → 「不是广告部写的」
    ('莉莉娅自己答:**「极简哲学」**——**不是**——**广告**——**部**——**写**——**的**——**是**——**总经办**——**或**——**战略**——**部**——**写**——**的**——**她**——**专题第二篇**——**她**——**要**——**拍**——**的**——**是**——**这种**——**跨**——**部门**——**的**——**字**——**背后**——**的**——**人**。',
     '莉莉娅自己答:**「极简哲学」**——**不是**——**广告部**——**写**——**的**——**总经办**——**或**——**战略部**——**写**——**的**——**她**——**专题第二篇**——**要**——**拍**——**的**——**是**——**这种**——**跨**——**部门**——**的字**——**背后**——**的**——**人**。'),
]

for old, new in replacements:
    if old in text:
        text = text.replace(old, new)
        print(f'  ✓ 替换: {old[:30]}')
    else:
        print(f'  ✗ 没找到: {old[:30]}')

with open(path, 'w', encoding='utf-8') as f:
    f.write(text)
