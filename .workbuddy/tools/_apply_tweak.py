def apply(path, reps):
    p = pathlib.Path(path)
    t = p.read_text(encoding="utf-8")
    log = []
    for old, new, cnt in reps:
        c = t.count(old)
        if c != cnt:
            log.append(f"  FAIL count={c} expected={cnt} :: {old[:44]}")
            continue
        t = t.replace(old, new)
        log.append(f"  OK x{cnt} :: {old[:36]}")
    p.write_text(t, encoding="utf-8")
    print("==", p.name)
    for l in log:
        print(l)


